# رسائل تم معالجتها مسبقاً لتجنب التكرار
processed_messages = set()

# دالة لاكتشاف ما إذا كانت الرسالة إعلان
def is_advertiser_message(text):

    if len(text.splitlines()) >= 6:
        return True
    if any(kw in text for kw in advertiser_keywords):
        return True
    if re.search(r"\+966\d{9}", text):
        return True
    if re.search(r"\b05\d{8}\b", text):
        return True
    if re.search(r"[أ-ي]\W?\.\W?[أ-ي]", text):  # للكشف عن نقاط متقطعة مثل "تــ.ــقرير"
        return True
    return False

# دالة لتشغيل جلسة حساب واحد
async def run_bot(account):
    session_folder = f"sessions/{account['name']}"
    os.makedirs(session_folder, exist_ok=True)
    session_path = os.path.join(session_folder, account['name'])

    client = TelegramClient(session_path, account["api_id"], account["api_hash"])

    @client.on(events.NewMessage(chats=None))
    async def detect_customer(event):
        message_text = event.message.text.lower()
        message_id = event.message.id
        chat_id = event.chat_id
        unique_key = (chat_id, message_id)

        if unique_key in processed_messages:
            return

        if any(keyword in message_text for keyword in keywords):
            if is_advertiser_message(message_text):
                print(f"⚠️ [{account['name']}] تم تجاهل رسالة مُعلِن.")
                return

            processed_messages.add(unique_key)

            try:
                sender = await event.get_sender()
            except Exception:
                sender = None

            chat = await event.get_chat()

            username = f"@{sender.username}" if sender and sender.username else "غير متوفر"
            msg_id = event.message.id

            if hasattr(chat, 'username') and chat.username:
                message_link = f"https://t.me/{chat.username}/{msg_id}"
            else:
                message_link = "رابط غير متاح (المجموعة خاصة)"

            final_message = (
                f"🔔 **تم رصد زبون مهتم بالخدمة!**\n\n"
                f"**نص رسالته:**\n{event.message.text}\n\n"
                f"**اسم المستخدم للتواصل:** {username}\n"
                f"**رابط الرسالة:** {message_link}"
            )

            try:
                await client.send_message(target_group, final_message, parse_mode='markdown')
                print(f"📢 [{account['name']}] تم إرسال تنبيه.")
            except FloodWaitError as e:
                print(f"⏳ [{account['name']}] تأخير بسبب Flood: {e.seconds} ثانية.")
                await asyncio.sleep(e.seconds)
            except Exception as e:
                print(f"❌ [{account['name']}] خطأ أثناء الإرسال: {e}")

    await client.start()
    print(f"✅ [{account['name']}] البوت جاهز ويعمل...")
    await client.run_until_disconnected()

# كود لإيهام Render أن هناك خدمة ويب تعمل لتجنب Port scan timeout
class HealthCheckHandler(BaseHTTPRequestHandler):
    def do_GET(self):
        self.send_response(200)
        self.end_headers()
        self.wfile.write(b"Bot is running!")

    def log_message(self, format, *args):
        # تعطيل سجلات السيرفر لتجنب الزحام في الـ Logs
        return

def run_health_check_server():
    port = int(os.environ.get("PORT", 8080))
    server = HTTPServer(('0.0.0.0', port), HealthCheckHandler)
    print(f"✅ Health check server started on port {port}")
    server.serve_forever()

# دالة تشغيل جميع الحسابات
async def main():
    # تشغيل سيرفر الـ Health Check في خلفية منفصلة
    threading.Thread(target=run_health_check_server, daemon=True).start()
    
    await asyncio.gather(*[run_bot(account) for account in accounts])

if __name__ == "__main__":
    try:
        asyncio.run(main())
    except KeyboardInterrupt:
        print("👋 تم إيقاف البوت.")
