# Runner
# ============================================================
def _run(label, cases, expect_accept):
    print(f"\n=== {label} ({len(cases)} cases, expect={'ACCEPT' if expect_accept else 'REJECT'}) ===")
    fails = []
    for t in cases:
        r = analyze_request(t)
        got = r.is_request
        ok = (got == expect_accept)
        if not ok:
            fails.append((t, got, r.reason, r.intent_type, round(r.confidence, 2)))
    if fails:
        # show first 15 failures in detail
        for t, got, reason, itype, conf in fails[:15]:
            tag = "ACCEPT" if got else "REJECT"
            disp = t.replace("\n", "\\n")
            if len(disp) > 70:
                disp = disp[:67] + "..."
            print(f"  ❌ expected {'ACCEPT' if expect_accept else 'REJECT'} got {tag} "
                  f"conf={conf} reason={reason} intent={itype} | {disp}")
        if len(fails) > 15:
            print(f"  ... and {len(fails)-15} more failures")
    passed = len(cases) - len(fails)
    print(f"  → {passed}/{len(cases)} passed ({len(fails)} failed)")
    return passed, len(fails)


