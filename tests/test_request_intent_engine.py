    fp = r_fail                          # genuine rejects wrongly accepted
    tn = r_pass                          # correctly rejected

    total_pos = len(ACCEPT_CASES)
    total_neg = len(REJECT_CASES)
    precision = tp / (tp + fp) if (tp + fp) else 0.0
    recall = tp / (tp + fn) if (tp + fn) else 0.0
    f1 = (2 * precision * recall / (precision + recall)) if (precision + recall) else 0.0
    accuracy = (tp + tn) / (total_pos + total_neg) if (total_pos + total_neg) else 0.0
    fp_rate = fp / total_neg if total_neg else 0.0
    fn_rate = fn / total_pos if total_pos else 0.0

    print("\n" + "=" * 72)
    print("METRICS (ACCEPT corpus = positives, REJECT corpus = negatives)")
    print("=" * 72)
    print(f"  ACCEPT corpus: {total_pos} cases  | TP={tp}  FN={fn}  → Recall={recall*100:.1f}%")
